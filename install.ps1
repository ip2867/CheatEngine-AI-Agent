# CheatEngine AI Agent -- installer
#
# Drops a tiny loader into Cheat Engine's autorun folder so the bridge starts
# with CE, and writes an MCP client config snippet you can paste.
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File install.ps1
#   powershell -ExecutionPolicy Bypass -File install.ps1 -CePath "D:\Cheat Engine"
#   powershell -ExecutionPolicy Bypass -File install.ps1 -Uninstall
#
# No administrator rights are needed: only CE's autorun folder is touched, and
# that folder is writable by the installing user.

[CmdletBinding()]
param(
    [string]$CePath = "",
    [switch]$Uninstall
)

$ErrorActionPreference = "Stop"
$Here = Split-Path -Parent $MyInvocation.MyCommand.Path
$Bridge = Join-Path $Here "ce\ce_ai_bridge.lua"
$LoaderName = "zz_ce_ai_agent.lua"

function Find-CePath {
    param([string]$Hint)

    if ($Hint -and (Test-Path (Join-Path $Hint "cheatengine-x86_64.exe"))) {
        return (Resolve-Path $Hint).Path
    }

    $candidates = @(
        "C:\Program Files\Cheat Engine",
        "C:\Program Files (x86)\Cheat Engine",
        "$env:LOCALAPPDATA\Programs\Cheat Engine"
    )
    foreach ($c in $candidates) {
        if (Test-Path (Join-Path $c "cheatengine-x86_64.exe")) { return $c }
    }

    # Fall back to the running process, then the registry.
    $proc = Get-Process -Name "cheatengine-x86_64", "cheatengine-i386" -ErrorAction SilentlyContinue |
            Select-Object -First 1
    if ($proc -and $proc.Path) { return (Split-Path -Parent $proc.Path) }

    foreach ($key in @(
        "HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\Cheat Engine_is1",
        "HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\Cheat Engine_is1"
    )) {
        if (Test-Path $key) {
            $loc = (Get-ItemProperty $key -ErrorAction SilentlyContinue).InstallLocation
            if ($loc -and (Test-Path (Join-Path $loc "cheatengine-x86_64.exe"))) {
                return $loc.TrimEnd("\")
            }
        }
    }
    return ""
}

$ce = Find-CePath -Hint $CePath
if (-not $ce) {
    Write-Host "Could not locate Cheat Engine." -ForegroundColor Red
    Write-Host "Re-run with:  install.ps1 -CePath `"D:\path\to\Cheat Engine`""
    exit 1
}

$autorun = Join-Path $ce "autorun"
Write-Host "Cheat Engine : $ce"
Write-Host "autorun      : $autorun"

if ($Uninstall) {
    $loaderPath = Join-Path $autorun $LoaderName
    if (Test-Path $loaderPath) {
        Remove-Item $loaderPath -Force
        Write-Host "Removed $loaderPath" -ForegroundColor Yellow
    } else {
        Write-Host "Nothing to remove (loader not installed)."
    }
    Write-Host "Restart Cheat Engine for the change to take effect."
    exit 0
}

if (-not (Test-Path $Bridge)) {
    Write-Host "Missing $Bridge -- the package looks incomplete." -ForegroundColor Red
    exit 1
}

if (-not (Test-Path $autorun)) {
    Write-Host "No autorun folder in $ce -- is this a portable build?" -ForegroundColor Red
    Write-Host "For a portable CE, put this folder wherever you like and load the"
    Write-Host "bridge manually from its Lua Engine:"
    Write-Host "    dofile([[$(Join-Path $Here 'ce\ce_ai_bridge.lua')]])"
    exit 1
}

# The loader stays trivial on purpose: all logic lives in the package folder so
# it can be edited without touching a Program Files directory.
$loader = @"
-- CheatEngine AI Agent -- autorun loader (generated by install.ps1)
-- Loads the bridge from the package directory. Edit the bridge there, not here.
local ok, err = pcall(dofile, [[$Bridge]])
if not ok then
  print('[CE-AI] bridge failed to load: ' .. tostring(err))
end
"@

$loaderPath = Join-Path $autorun $LoaderName
try {
    Set-Content -Path $loaderPath -Value $loader -Encoding ASCII -ErrorAction Stop
} catch {
    Write-Host "Cannot write to $autorun (permission denied)." -ForegroundColor Red
    Write-Host "Run this installer as Administrator, or use -CePath for a portable CE."
    exit 1
}
Write-Host "Installed loader: $loaderPath" -ForegroundColor Green

# Emit an MCP config snippet with this machine's real paths.
$python = (Get-Command python -ErrorAction SilentlyContinue).Source
if (-not $python) { $python = "python" }
$serverPy = Join-Path $Here "mcp\ce_mcp_server.py"

$mcpConfig = [ordered]@{
    mcpServers = [ordered]@{
        cheatengine = [ordered]@{
            command = $python
            args    = @($serverPy)
            env     = [ordered]@{
                CE_AI_ENABLE_WRITES = "1"
                CE_AI_PIPE          = "\\.\pipe\CE_AI_Bridge_v1_0"
            }
            timeout = 120
        }
    }
}
$configPath = Join-Path $Here "config\mcp-generated.json"
$mcpConfig | ConvertTo-Json -Depth 8 | Set-Content -Path $configPath -Encoding UTF8
Write-Host "Wrote MCP config: $configPath" -ForegroundColor Green

Write-Host ""
Write-Host "Next steps" -ForegroundColor Cyan
Write-Host "  1. Restart Cheat Engine. Its Lua Engine should print:"
Write-Host "       [CE-AI] listening on CE_AI_Bridge_v1_0 (v0.4.0)"
Write-Host "  2. Add this server to your AI client's MCP config:"
Write-Host "       $configPath"
Write-Host "  3. Attach CE to a target, then ask the agent to analyse it."
Write-Host ""
Write-Host "Set CE_AI_ENABLE_WRITES=0 to keep the agent read-only."
